def count_d_o_points():
    d_o_game_events = list(filter(lambda ev: ev["y"] in ["S", "O", "H"], game_events))
    d_o_points = {
        "a": {
            "offence_points": 0,
            "defence_points": 0
        },
        "h": {
            "offence_points": 0,
            "defence_points": 0
        }
    }
    # -1 : a
    # +1 : h
    side = 0
    starting_offence = 0
    for e in d_o_game_events:
        if e["y"] == "O":
            starting_offence = e["e"]
            side = starting_offence
        if e["y"] == "H":
            side = "h" if starting_offence == "a" else "a"
        if e["y"] == "S":
            side_check = e["e"]
            if side != side_check:
                d_o_points[e["e"]]["defence_points"] += 1
            else:
                d_o_points[e["e"]]["offence_points"] += 1
            side = "h" if e["e"] == "a" else "a"
    return d_o_points


def count_disc_possession():
    possession_game_events = list(filter(lambda ev: ev["y"] in ["T", "S", "O", "H"], game_events))
    disc_possession = {
        "a": 0,
        "h": 0,
        "total": possession_game_events[-1]["t"]
    }
    tmp_time = 0
    starting_offence = ""
    side = ""
    for e in possession_game_events:
        if e["y"] == "O":
            starting_offence = e["e"]
            side = starting_offence
        if e["y"] == "S":
            disc_possession[side] += e["t"] - tmp_time
            side = "h" if e["e"] == "a" else "a"
        if e["y"] == "H":
            disc_possession[side] += e["t"] - tmp_time
            side = "h" if starting_offence == "a" else "a"
        if e["y"] == "T":
            disc_possession[side] += e["t"] - tmp_time

        tmp_time = e["t"]
    disc_possession["a"] = round(disc_possession["a"] / disc_possession["total"] * 100, 1)
    disc_possession["h"] = round(disc_possession["h"] / disc_possession["total"] * 100, 1)
    return disc_possession


def count_turnovers():
    turnover_stats = {
        "a": len(list(filter(lambda ev: ev["y"] == "T" and ev["e"] == "a", game_events))),
        "h": len(list(filter(lambda ev: ev["y"] == "T" and ev["e"] == "h", game_events)))
    }
    return turnover_stats


def count_timeouts():
    timeout_stats = {
        "a": len(list(filter(lambda ev: ev["y"] == "TO" and ev["e"] == "a", game_events))),
        "h": len(list(filter(lambda ev: ev["y"] == "TO" and ev["e"] == "h", game_events)))
    }
    return timeout_stats


def count_points_per_player():
    points_stats = {
        "a": {},
        "h": {}
    }
    for e in filter(lambda ev: ev["y"] == "S", game_events):
        # e["e"] home/away
        scorer_no = str(e["s"])
        scorer = players[e["e"]][scorer_no]
        assist_no = str(e["a"])
        assist = players[e["e"]][assist_no]
        if scorer_no not in points_stats[e["e"]]:
            points_stats[e["e"]][scorer_no] = {
                "scores": 0,
                "assists": 0,
                "name": scorer,
                "no": scorer_no
            }
        if assist_no not in points_stats[e["e"]]:
            points_stats[e["e"]][assist_no] = {
                "scores": 0,
                "assists": 0,
                "name": assist,
                "no": assist_no
            }
        points_stats[e["e"]][scorer_no]["scores"] += 1
        points_stats[e["e"]][assist_no]["assists"] += 1
    point_stats_sorted = {
        "a": {
            "total": sorted(list(points_stats["a"].values()), key=lambda el: el["scores"]+el["assists"], reverse=True),
            "assists": sorted(list(points_stats["a"].values()), key=lambda el: el["assists"], reverse=True),
            "points": sorted(list(points_stats["a"].values()), key=lambda el: el["scores"], reverse=True)
        },
        "h": {
            "total": sorted(list(points_stats["h"].values()), key=lambda el: el["scores"]+el["assists"], reverse=True),
            "assists": sorted(list(points_stats["h"].values()), key=lambda el: el["assists"], reverse=True),
            "points": sorted(list(points_stats["h"].values()), key=lambda el: el["scores"], reverse=True)
        }
    }

    return point_stats_sorted


